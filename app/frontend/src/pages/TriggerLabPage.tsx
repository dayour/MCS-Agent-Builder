// Returns a scenario-specific "what happened" detail for a completed CoT step.
function buildStepDetail(step: LabCoTStep, scenario: AgentScenario): string | undefined {
  const t = step.label.toLowerCase();
  const connector = (step.connectorKey ?? '').toLowerCase();
  const fm = scenario.storyFields.reduce<Record<string, string>>((acc, f) => ({ ...acc, [f.key]: f.value }), {});
  const subject = fm.customer ?? fm.company ?? fm.client ?? fm.opportunity ?? fm.name ?? '';
  const amount  = fm.amount ?? fm.value ?? fm.budget ?? '';

  if (step.id === 'trigger' || step.id === 'respond') return undefined;

  if (step.id === 'knowledge' || step.id.startsWith('knowledge-')) {
    // For individual knowledge source steps, use the capability name to generate a relevant detail
    const capLower = (step.capabilityName ?? '').toLowerCase();
    if (capLower.includes('software') || capLower.includes('catalog'))
      return 'Checked catalog — cross-referenced against approved items';
    if (capLower.includes('troubleshoot') || capLower.includes('runbook'))
      return 'Found troubleshooting procedures and known issues';
    if (capLower.includes('knowledge') || capLower.includes('help'))
      return 'Located 2 matching files in SharePoint';
    const docNames = scenario.storyFields
      .filter(f => f.value.match(/\.(pdf|docx|xlsx)/i))
      .map(f => f.value)
      .slice(0, 2);
    if (docNames.length) return `Found ${docNames.join(', ')} and 2 related items`;
    return 'Searched 4 documents — 2 highly relevant matches found';
  }

  // ── ServiceNow — always check connector first to avoid fallthrough ─────────
  if (connector === 'servicenow' || t.includes('servicenow') || t.includes('incident')) {
    const isEscalation = t.includes('escalat');
    if (isEscalation)
      return subject ? `Escalation ticket created for ${subject} — Priority: High, assigned to Level 2 Support` : 'Escalation ticket created — Priority: High, assigned to Level 2 Support';
    return subject ? `Incident record created for ${subject} in ServiceNow` : 'Incident record created in ServiceNow';
  }

  // Lookup / search / retrieve
  if (t.includes('look up') || t.includes('search') || t.includes('fetch') || t.includes('retrieve') || t.includes('get') || t.includes('find')) {
    if ((t.includes('pric') || t.includes('catalog')) && subject)
      return `Pricing sheet for ${subject} retrieved — 3 tiers found (Starter, Business, Enterprise)`;
    if (t.includes('pric') || t.includes('catalog'))
      return 'Pricing sheet retrieved — 3 tiers: Starter $299/mo, Business $799/mo, Enterprise $2,400/mo';
    if ((t.includes('record') || t.includes('dataverse') || t.includes('opportunity')) && subject)
      return `${subject} found in Dataverse — Status: Active, account since 2021`;
    if (t.includes('sharepoint') || t.includes('file') || t.includes('document'))
      return 'Located 2 matching files in SharePoint';
    if (t.includes('email') || t.includes('thread'))
      return subject ? `Found 3 recent emails from ${subject}` : '3 relevant emails retrieved';
    return subject ? `Data for ${subject} retrieved successfully` : 'Data retrieved';
  }

  // Create / generate / draft
  if (t.includes('create') || t.includes('generate') || t.includes('write') || t.includes('draft') || t.includes('prepare') || t.includes('populate') || t.includes('fill')) {
    if (connector === 'word' || ((t.includes('word') || t.includes('quote') || t.includes('report') || t.includes('template')) && !t.includes('record') && !t.includes('ticket'))) {
      const name = subject ? `Quote_${subject.replace(/\s+/g, '_')}.docx` : 'Quote.docx';
      return `Generated ${name} — 3 pages, includes pricing breakdown${amount ? ` ($${amount})` : ''}`;
    }
    if (t.includes('excel') || t.includes('spreadsheet')) {
      const name = subject ? `Report_${subject.replace(/\s+/g, '_')}.xlsx` : 'Report.xlsx';
      return `Created ${name} — ${scenario.expectedActions.length * 4} rows populated`;
    }
    if (t.includes('record') || t.includes('dataverse') || t.includes('opportunity'))
      return subject ? `Opportunity record created for ${subject}${amount ? ` — deal value $${amount}` : ''}` : 'Record created in Dataverse';
    if (t.includes('task') || t.includes('planner'))
      return subject ? `Task assigned to ${subject} — due in 5 business days` : 'Task created in Planner';
    return subject ? `Draft created for ${subject}` : 'Draft created successfully';
  }

  // Send / notify / message
  if (t.includes('send') || t.includes('notify') || t.includes('message') || t.includes('email') || t.includes('reply') || t.includes('post')) {
    const preview = subject ? `"${scenario.title} is ready for review..."` : '"Your request has been processed..."';
    if (t.includes('teams') || t.includes('chat') || t.includes('reply'))
      return subject ? `Message delivered to ${subject} in Teams: ${preview}` : `Teams message sent: ${preview}`;
    if (t.includes('email') || t.includes('mail') || t.includes('outlook'))
      return subject ? `Email sent to ${subject}: ${preview}` : `Email sent: ${preview}`;
    return subject ? `${subject} notified` : 'Notification sent';
  }

  // Update / edit / modify
  if (t.includes('update') || t.includes('edit') || t.includes('modify') || t.includes('set') || t.includes('change')) {
    return subject ? `${subject}'s record updated in Dataverse` : 'Record updated successfully';
  }

  return undefined;
}

// Determines whether a CoT step produces a viewable artifact and returns its content.
// Uses connectorKey as the primary signal. Verb checks use plain substring matching —
// never \b on stems like "creat" which won't match "create" due to word-boundary rules.
function buildArtifact(step: LabCoTStep, scenario: AgentScenario): LabCoTArtifact | undefined {
  const t        = step.label.toLowerCase();
  const connector = (step.connectorKey ?? '').toLowerCase();
  const cap       = (step.capabilityName ?? '').toLowerCase();
  const combined  = `${t} ${cap}`;

  const fm      = scenario.storyFields.reduce<Record<string, string>>((acc, f) => ({ ...acc, [f.key]: f.value }), {});
  const subject = fm.customer ?? fm.company ?? fm.client ?? fm.opportunity ?? fm.name ?? 'Customer';
  const slug    = subject.replace(/\s+/g, '_');
  const now     = new Date();

  const has = (...words: string[]) => words.some(w => combined.includes(w));

  // ── Planner — create OR update task ─────────────────────────────────────────
  if (connector === 'planner' || has('task', 'planner')) {
    if (has('get', 'retriev', 'fetch', 'read', 'search')) return undefined; // skip reads
    const isUpdate = has('update', 'track', 'modify');
    const assignee = fm.assignee ?? fm.owner ?? fm.requester ?? fm.from ?? 'Support Team';
    const dueDate  = new Date(Date.now() + 5 * 86400000).toLocaleDateString();
    return {
      name: isUpdate ? `Task update — ${scenario.title}` : `Task — ${scenario.title}`,
      extension: 'planner',
      preview: isUpdate
        ? `**Task:** ${scenario.title}\n**Status:** In Progress → Resolved\n**Updated:** ${now.toLocaleString()}\n**Updated by:** Agent\n\n**Resolution notes:** ${scenario.description}`
        : `**Task:** ${scenario.title}\n**Assigned to:** ${assignee}\n**Due date:** ${dueDate}\n**Priority:** High\n**Status:** Not started\n\n**Description:** ${scenario.description}`,
    };
  }

  // ── Outlook — send or reply ──────────────────────────────────────────────────
  if (connector === 'outlook' || has('email', ' mail')) {
    if (!has('send', 'reply', 'draft', 'compose')) return undefined; // skip reads
    const isReply   = has('reply');
    const recipient = fm.customer ?? fm.company ?? fm.client ?? fm.name ?? 'Customer';
    return {
      name: isReply ? `Re: ${scenario.title}` : `Email to ${recipient}`,
      extension: 'email',
      preview: isReply
        ? `**To:** ${recipient}\n**Subject:** Re: ${scenario.title}\n**From:** Support Agent\n**Sent:** ${now.toLocaleString()}\n\nHi,\n\nFollowing up on your recent request — ${scenario.description}\n\n**Steps completed:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}\n\nReply to this email if you need further assistance.`
        : `**To:** ${recipient}\n**Subject:** ${scenario.title} — Follow-up\n**From:** Support Agent\n**Sent:** ${now.toLocaleString()}\n\nHi ${recipient},\n\n${scenario.description}\n\n**What we did:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}\n\nLet us know if anything else comes up.`,
    };
  }

  // ── Teams — post or send message ────────────────────────────────────────────
  if (connector === 'teams' || has('teams', 'channel')) {
    if (!has('post', 'send', 'message', 'alert', 'notify')) return undefined;
    return {
      name: `Teams message — ${scenario.title}`,
      extension: 'teams',
      preview: `**Channel:** #support-alerts\n**Posted by:** Support Agent\n**Time:** ${now.toLocaleString()}\n\n**Update: ${scenario.title}**\n\n${scenario.description}\n\n**Actions taken:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}\n\n@support-team please review and confirm resolution.`,
    };
  }

  // ── SharePoint — create or log item ─────────────────────────────────────────
  if (connector === 'sharepoint' || has('sharepoint')) {
    if (!has('create', 'add', 'log', 'update', 'post')) return undefined;
    return {
      name: `Support log — ${scenario.title}`,
      extension: 'sharepoint',
      preview: `**List:** Support Interactions\n**Title:** ${scenario.title}\n**Status:** Resolved\n**Customer:** ${subject}\n**Date:** ${now.toLocaleDateString()}\n**Time:** ${now.toLocaleTimeString()}\n\n**Summary:** ${scenario.description}\n\n**Actions logged:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}`,
    };
  }

  // ── ServiceNow — create incident / record ───────────────────────────────────
  if (connector === 'servicenow' || has('servicenow', 'incident')) {
    if (!has('create', 'add', 'log', 'escalat', 'update', 'raise')) return undefined;
    const isEscalation = has('escalat');
    const requester = fm.requester ?? fm.customer ?? fm.name ?? fm.from ?? 'Employee';
    const ticketNum = `INC${String(Math.floor(Math.random() * 9000000 + 1000000))}`;
    return {
      name: isEscalation ? `Escalation — ${scenario.title}` : `Incident — ${scenario.title}`,
      extension: 'servicenow',
      preview: isEscalation
        ? `**Record type:** Incident (Escalated)\n**Number:** ${ticketNum}\n**Caller:** ${requester}\n**Category:** ${scenario.title}\n**Priority:** 2 — High\n**Assignment group:** Level 2 Support\n**State:** New\n**Created:** ${now.toLocaleString()}\n\n**Short description:** ${scenario.title}\n\n**Description:**\n${scenario.description}\n\n**Steps already taken:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}`
        : `**Record type:** Incident\n**Number:** ${ticketNum}\n**Caller:** ${requester}\n**Category:** ${scenario.title}\n**Priority:** 3 — Moderate\n**Assignment group:** IT Help Desk\n**State:** New\n**Created:** ${now.toLocaleString()}\n\n**Short description:** ${scenario.title}\n\n**Description:**\n${scenario.description}`,
    };
  }

  // ── Dataverse — add row / escalation ────────────────────────────────────────
  if (connector === 'dataverse' || has('dataverse', ' row', 'escalat')) {
    if (!has('add', 'create', 'escalat', 'log', 'update')) return undefined;
    return {
      name: `Escalation record — ${scenario.title}`,
      extension: 'dataverse',
      preview: `**Record type:** Escalation\n**Case:** ${scenario.title}\n**Customer:** ${subject}\n**Created:** ${now.toLocaleString()}\n**Escalated to:** Level 2 Support\n**Priority:** High\n\n**Issue summary:** ${scenario.description}\n\n**Steps already taken:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}`,
    };
  }

  // ── Word document ────────────────────────────────────────────────────────────
  if (connector === 'word' || has('word', 'document', 'report', 'template', 'proposal')) {
    if (!has('create', 'generate', 'draft', 'write', 'fill', 'populate')) return undefined;
    return {
      name: `${slug}_document.docx`,
      extension: 'docx',
      preview: `**Document:** ${scenario.title}\n**Prepared:** ${now.toLocaleDateString()}\n\n---\n\n${scenario.description}\n\n**Contents:**\n${scenario.expectedActions.map(a => `• ${a}`).join('\n')}`,
    };
  }

  // ── Excel ────────────────────────────────────────────────────────────────────
  if (connector === 'excel' || has('excel', 'spreadsheet')) {
    if (!has('create', 'generate', 'populate', 'fill')) return undefined;
    return {
      name: `Report_${slug}.xlsx`,
      extension: 'xlsx',
      preview: `**Report:** ${scenario.title}\n**Generated:** ${now.toLocaleString()}\n\n| Field | Value |\n|-------|-------|\n| Customer | ${subject} |\n| Status | Complete |\n| Actions taken | ${scenario.expectedActions.length} |\n| Date | ${now.toLocaleDateString()} |`,
    };
  }

  return undefined;
}

