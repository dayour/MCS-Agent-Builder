/** Structured info about what fired a trigger — platform, sender, and message content. */
interface TriggerMeta {
  platform?: string;  // e.g. 'Teams', 'Forms', 'Dataverse'
  sender?: string;    // human name from story fields
  message: string;    // the actual text or field summary
}

/** A document chunk retrieved from a knowledge source during a search step. */
interface RetrievedChunk {
  source: string;    // e.g. 'Pricing_Sheet_2024.docx · p.2'
  excerpt: string;   // the actual text snippet
  relevance: number; // 0.0–1.0
}

/** A simulated file artifact generated by an agent action step. */
interface LabCoTArtifact {
  name: string;                               // e.g. 'Quote_AcmeCorp.docx'
  extension: 'docx' | 'xlsx' | 'pdf' | 'email' | 'planner' | 'teams' | 'sharepoint' | 'dataverse' | 'servicenow';
  preview: string;                            // markdown-ish content for preview modal
}

interface LabCoTStep {
  id: string;
  label: string;
  detail?: string;
  connectorKey?: string;        // e.g. 'Teams', 'Word', 'Dataverse' — maps to /component-icons/{key}16.svg
  capabilityName?: string;      // matched capability name from agent config (e.g. "Send a Teams message")
  artifact?: LabCoTArtifact;
  retrievedChunks?: RetrievedChunk[];  // populated for knowledge search steps
  status: 'pending' | 'running' | 'complete' | 'failed' | 'skipped';
}

