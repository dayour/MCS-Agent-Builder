// Returns structured trigger metadata — who fired it, from where, and what they said/submitted.
function buildTriggerMeta(scenario: AgentScenario, fields: StoryField[], agentName?: string): TriggerMeta {
  const fieldMap = fields.reduce<Record<string, string>>((acc, f) => ({ ...acc, [f.key]: f.value }), {});
  const sender = fieldMap.from ?? fieldMap.sender ?? fieldMap.requester ?? fieldMap.user ?? fieldMap.name ?? undefined;

  // Derive the trigger message directly from buildPromptFromScenario (stripped of
  // the [SIMULATION MODE] suffix) so the trace always shows the exact text that was
  // sent to the agent. This eliminates inconsistencies from duplicating the logic.
  const scenarioWithFields: AgentScenario = { ...scenario, storyFields: fields };
  const rawPrompt = buildPromptFromScenario(scenarioWithFields);
  const message = rawPrompt.split('\n\n[SIMULATION MODE]')[0].trim();

  switch (scenario.triggerType) {
    case 'chat':
      return { platform: 'Teams', sender, message };
    case 'form':
      return { platform: 'Forms', sender, message };
    case 'record':
      return { platform: 'Dataverse', sender, message };
    case 'webhook':
      return { platform: 'Webhook', message };
    case 'recurrence':
      return { message };
    default:
      return { sender, message };
  }
}

function buildPromptFromScenario(scenario: AgentScenario): string {
  const fieldMap = scenario.storyFields.reduce<Record<string, string>>(
    (acc, f) => ({ ...acc, [f.key]: f.value }),
    {},
  );

  // Simulation instruction appended to every prompt so the agent describes
  // each action it would take — including connector calls it can't make for real.
  const simulationSuffix = `\n\n[SIMULATION MODE]: You do not have live connector access in this test. For each action you would take (e.g. creating a record, generating a document, sending a message), describe what you would do and show a realistic example of what it would produce. Be specific and complete — treat this as a dry-run demonstration of your full workflow.`;

  switch (scenario.triggerType) {
    case 'chat':
      return (fieldMap.message || Object.values(fieldMap)[0] || '') + simulationSuffix;
    case 'recurrence':
      return `[System: Scheduled trigger fired]\nThis is a ${fieldMap.frequency || 'Daily'} run at ${fieldMap.time || '9:00 AM'}.\nExecute your scheduled routine now.${simulationSuffix}`;
    default: {
      // Use field values directly (not Label: Value pairs) so the agent receives
      // natural context rather than a structured dump it might paraphrase verbatim.
      const context = scenario.storyFields.map(f => f.value).filter(Boolean).join('\n');
      return `[System: ${scenario.triggerLabel}]\n\n${context}\n\nProcess this event according to your instructions.${simulationSuffix}`;
    }
  }
}

// Convert raw markdown from the agent response into the format CopilotMessage's
// formatContent() already handles (bold, bullets, numbered lists, dividers).
function cleanResponse(text: string): string {
  return text
    // Strip pipe table rows (| col | col |) — they render as raw characters
    .replace(/^\|.*\|[ \t]*$/gm, '')
    // Strip table separator rows (|---|---|)
    .replace(/^[| \t:-]+\|[ \t:-]*$/gm, '')
    // Strip agent internal step markers (--- Step N — ...) and similar header lines
    .replace(/^---\s+.{0,80}\s+---\s*$/gm, '')
    // Strip blockquote lines starting with > (agent internal notes)
    .replace(/^>\s.*$/gm, '')
    // ## Heading / ### Heading → **Heading** (bold paragraph)
    .replace(/^#{1,4}\s+(.+)$/gm, '**$1**')
    // Fenced code blocks → unwrap content
    .replace(/```[a-z]*\n?([\s\S]*?)```/g, (_, inner) => inner.trim())
    // Inline code → plain text
    .replace(/`([^`]+)`/g, '$1')
    // Standalone horizontal rules → ---
    .replace(/^[-_*]{3,}\s*$/gm, '---')
    // Collapse 3+ blank lines to 2
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

