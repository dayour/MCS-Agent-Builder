// Returns the full capability object so callers can access .source for the connector icon
function findCapabilityForAction(actionText: string, capabilities: AgentConfig['capabilities']): AgentCapability | undefined {
  const actions = (capabilities || []).filter(c => c.type === 'action');
  if (actions.length === 0) return undefined;
  const t = actionText.toLowerCase();
  let bestMatch: AgentCapability | undefined;
  let bestScore = 0;
  for (const cap of actions) {
    const words = cap.name.toLowerCase().split(/\s+/).filter(w => w.length > 3);
    const score = words.filter(w => t.includes(w)).length;
    if (score > bestScore) { bestScore = score; bestMatch = cap; }
  }
  return bestScore > 0 ? bestMatch : undefined;
}

function guessConnector(text: string): string | undefined {
  const t = text.toLowerCase();
  // Use word-boundary checks to avoid false matches (e.g. "password" must not match "word")
  if (/\bword\b/.test(t) || /\bdocument\b/.test(t))           return 'Word';
  if (/\bexcel\b/.test(t) || /\bspreadsheet\b/.test(t))       return 'Excel';
  if (/\bteams\b/.test(t) || /\bmessage\b/.test(t) || /\bchat\b/.test(t) || /\breply\b/.test(t) || /\bmention\b/.test(t)) return 'Teams';
  if (/\bdataverse\b/.test(t) || /\brecord\b/.test(t) || /\brow\b/.test(t) || /\bopportunity\b/.test(t)) return 'Dataverse';
  if (/\bsharepoint\b/.test(t) || /\blibrary\b/.test(t) || /\bpricing\b/.test(t) || /\bcatalog\b/.test(t)) return 'SharePoint';
  if (/\boutlook\b/.test(t) || /\bemail\b/.test(t) || /\bmail\b/.test(t)) return 'Outlook';
  if (/\bonedrive\b/.test(t) || /\bfile\b/.test(t) || /\bfolder\b/.test(t)) return 'OneDrive';
  if (/\bforms\b/.test(t) || /\bform\b/.test(t))              return 'Forms';
  if (/\bplanner\b/.test(t) || /\btask\b/.test(t))            return 'Planner';
  if (/\bservicenow\b/.test(t) || /\bincident\b/.test(t))    return 'ServiceNow';
  return undefined;
}


function triggerConnector(triggerType: TriggerType): string | undefined {
  switch (triggerType) {
    case 'chat':      return 'Teams';
    case 'form':      return 'Forms';
    case 'record':    return 'Dataverse';
    case 'webhook':   return undefined;
    case 'recurrence': return undefined;
  }
}

function buildLabCoTSteps(
  scenario: AgentScenario,
  config: AgentConfig,
  // When provided (from planTurn), these replace scenario.expectedActions so CoT
  // and response are always derived from the same plan.
  plannedActions?: PlannedAction[],
  // Follow-up turns skip knowledge lookup — the agent already has context.
  includeKnowledge = true,
): LabCoTStep[] {
  const steps: LabCoTStep[] = [];

  // 1. Trigger
  steps.push({
    id: 'trigger',
    label: scenario.triggerLabel,
    connectorKey: triggerConnector(scenario.triggerType),
    status: 'pending',
  });

  // 2. Knowledge lookup (skipped for follow-up turns)
  if (includeKnowledge) {
    const knowledgeCaps = (config.capabilities || []).filter(c => c.type === 'knowledge');
    const files  = config.knowledge?.files ?? [];
    const hasWeb = config.knowledge?.webSearch;
    const hasSP  = config.knowledge?.specificSources;

    if (knowledgeCaps.length > 0) {
      knowledgeCaps.slice(0, 3).forEach((cap, ki) => {
        // Use shortCapabilityName to avoid "Searching Excel - Approved Software Catalog"
        // becoming "Searching Excel - [Approved Software Catalog]" with duplicate connector prefix
        const shortName = shortCapabilityName(cap.name);
        steps.push({
          id: `knowledge-${ki}`,
          label: `Searching ${shortName} for context`,
          connectorKey: cap.source,
          capabilityName: cap.name,
          status: 'pending',
        });
      });
      if (hasWeb) {
        steps.push({ id: 'knowledge-web', label: 'Searching the web for context', connectorKey: undefined, status: 'pending' });
      }
    } else if (files.length > 0 || hasWeb || hasSP) {
      const parts: string[] = [];
      if (files.length > 0) parts.push(...files.slice(0, 2).map(f => f.name));
      if (hasSP) parts.push('SharePoint');
      if (hasWeb) parts.push('Web search');
      const knowledgeConnector = hasSP ? 'SharePoint' : files.length > 0 ? 'OneDrive' : undefined;
      steps.push({
        id: 'knowledge',
        label: knowledgeConnector ? `Searching ${knowledgeConnector} for context` : 'Searching knowledge base',
        detail: parts.join(' · '),
        connectorKey: knowledgeConnector,
        status: 'pending',
      });
    }
  }

  // 3. Actions — use the LLM plan when available, otherwise fall back to scenario.expectedActions
  const actionItems: Array<{ label: string; connectorHint: string | null }> = plannedActions && plannedActions.length > 0
    ? plannedActions.map(a => ({ label: a.action, connectorHint: a.connector }))
    : scenario.expectedActions.map(a => ({ label: a, connectorHint: null }));

  actionItems.slice(0, 5).forEach(({ label: rawLabel, connectorHint }, i) => {
    const cap    = findCapabilityForAction(rawLabel, config.capabilities);
    const connKey = cap?.source ?? (connectorHint ?? undefined) ?? guessConnector(rawLabel);
    // Clean up labels where the LLM echoes the capability name, e.g.
    // "Post message in Post message in a chat or channel chat..." → "Post message in chat..."
    let label = rawLabel;
    if (cap) {
      const capShort = shortCapabilityName(cap.name);
      const capLower = capShort.toLowerCase();
      const labelLower = label.toLowerCase();
      const idx = labelLower.indexOf(capLower);
      if (idx !== -1) {
        // Check if the text before the match duplicates part of the capability name
        const before = label.slice(0, idx).trim();
        const capStart = capShort.split(/\s+/).slice(0, 2).join(' ').toLowerCase();
        if (before.toLowerCase().endsWith(capStart) || capLower.startsWith(before.toLowerCase())) {
          // Remove the redundant prefix — keep only the capability name + text after it
          label = label.slice(idx);
        }
      }
    }
    steps.push({
      id: `action-${i}`,
      label: label.replace(/\[\[/g, '').replace(/\]\]/g, ''),
      connectorKey: connKey,
      capabilityName: cap?.name,
      status: 'pending',
    });
  });

  // 4. Compose response
  steps.push({ id: 'respond', label: 'Composing response', status: 'pending' });

  return steps;
}

// Ask a fast model which actions the agent would take for this message.
// Returns a structured list that drives both the CoT steps and the response grounding,
// keeping them in sync so the CoT never shows different actions than the response.
async function planTurn(
  message: string,
  agentConfig: AgentConfig,
  history: Array<{ role: string; content: string }>,
): Promise<PlannedAction[]> {
  const actionCaps = (agentConfig.capabilities || []).filter(c => c.type === 'action');
  if (actionCaps.length === 0) return [];

  const capsList = actionCaps.map(c => `- ${c.name}${c.source ? ` (${c.source})` : ''}`).join('\n');
  const recentCtx = history.slice(-4)
    .map(m => `${m.role === 'user' ? 'User' : 'Agent'}: ${m.content.slice(0, 200)}`)
    .join('\n');

  try {
    const raw = await callModel({
      model: 'fast',
      maxTokens: 400,
      system: `You are ${agentConfig.name}. Your available action capabilities:\n${capsList}\n\nDecide which actions you would take for the user's message. Reply ONLY with a JSON array — no prose:\n[{"action": "concise description of what you do", "connector": "ServiceName or null"}]\nMax 5 items. Only include capabilities listed above.`,
      messages: [
        ...(recentCtx ? [
          { role: 'user' as const, content: `Conversation context:\n${recentCtx}` },
          { role: 'assistant' as const, content: 'Understood, I have the context.' },
        ] : []),
        { role: 'user' as const, content: message },
      ],
    });
    const jsonStr = raw.match(/\[[\s\S]*?\]/s)?.[0] ?? '[]';
    const parsed = JSON.parse(jsonStr);
    return Array.isArray(parsed) ? (parsed as PlannedAction[]).slice(0, 5) : [];
  } catch {
    return [];
  }
}

// "Tool: Word Online - Populate a template" → "Populate a template"
function shortCapabilityName(name: string): string {
  const dashIdx = name.lastIndexOf(' - ');
  if (dashIdx !== -1) return name.slice(dashIdx + 3);
  const colonIdx = name.indexOf(': ');
  if (colonIdx !== -1) return name.slice(colonIdx + 2);
  return name;
}
// "Tool: Word Online - Populate a template" → "TOOL"
function capabilityTypeLabel(name: string): string {
  const colonIdx = name.indexOf(': ');
  return colonIdx !== -1 ? name.slice(0, colonIdx).toUpperCase() : 'TOOL';
}
// "Tool: Word Online - Populate a template" → "Word Online"
function capabilityServiceName(name: string): string {
  const colonIdx = name.indexOf(': ');
  if (colonIdx === -1) return '';
  const afterColon = name.slice(colonIdx + 2);
  const dashIdx = afterColon.lastIndexOf(' - ');
  return dashIdx !== -1 ? afterColon.slice(0, dashIdx) : '';
}

// Maps a free-form service/connector name to the icon key used in /component-icons/{key}16.svg.
// Falls back to the raw value — the onError handler in the <img> will hide any broken images.
function normalizeConnectorIconKey(key: string): string {
  const lower = key.toLowerCase();
  if (lower.includes('sharepoint')) return 'SharePoint';
  if (lower.includes('excel'))      return 'Excel';
  if (lower.includes('word'))       return 'Word';
  if (lower.includes('onedrive'))   return 'OneDrive';
  if (lower.includes('outlook') || lower.includes('email')) return 'Outlook';
  if (lower.includes('teams'))      return 'Teams';
  if (lower.includes('dataverse'))  return 'Dataverse';
  if (lower.includes('salesforce')) return 'Salesforce';
  if (lower.includes('servicenow')) return 'ServiceNow';
  if (lower.includes('forms'))      return 'Forms';
  if (lower.includes('planner'))    return 'Planner';
  return key;
}

// Returns a Word or Excel icon for a retrieved-chunk source string (e.g. "Sales_FAQ.docx · p.1").
// Returns null for unknown/unrecognised file types.
function getChunkFileIcon(source: string): React.ReactNode | null {
  const lower = source.toLowerCase();
  if (lower.includes('.docx') || lower.includes('.doc')) {
    return <img src="/component-icons/WordFile16.svg" alt="Word" style={{ width: 14, height: 14, flexShrink: 0 }} />;
  }
  if (lower.includes('.xlsx') || lower.includes('.xls') || lower.includes('.csv')) {
    return <img src="/component-icons/ExcelFile16.svg" alt="Excel" style={{ width: 14, height: 14, flexShrink: 0 }} />;
  }
  if (lower.includes('sharepoint') || lower.includes('.aspx')) {
    return <img src="/component-icons/SharePointSite16.svg" alt="SharePoint" style={{ width: 14, height: 14, flexShrink: 0 }} />;
  }
  return null;
}

// Replace the connector name where it naturally appears in the label with a ComponentPill.
// If the connector name doesn't appear in the label verbatim, returns plain text (no pill).
function renderInlineLabel(
  label: string,
  connectorKey: string | undefined,
  capabilityName: string | undefined,
  onPillClick?: (fullName: string, e: React.MouseEvent<HTMLSpanElement>) => void,
  error?: boolean,
  onErrorClick?: () => void,
): React.ReactNode {
  if (!connectorKey && !capabilityName) return label;
  const fullName  = capabilityName || connectorKey!;
  const pillLabel = shortCapabilityName(fullName);

  // Try to find the pill's text in the label — prefer the short capability name,
  // then fall back to the connector service name. This ensures "Searching [Product documentation]
  // for context" works even when connectorKey="SharePoint" isn't in the label text.
  const candidates = [pillLabel, capabilityName, connectorKey].filter(Boolean) as string[];
  let matchIdx = -1;
  let matchLen = 0;
  for (const term of candidates) {
    const idx = label.toLowerCase().indexOf(term.toLowerCase());
    if (idx !== -1) { matchIdx = idx; matchLen = term.length; break; }
  }
  if (matchIdx === -1) return label; // nothing found in label — don't force a pill

  const before = label.slice(0, matchIdx);
  const after  = label.slice(matchIdx + matchLen);

  // Derive icon key: prefer explicit connectorKey, then parse from capabilityName prefix
  // (e.g. "SharePoint - Sales Playbook" → "SharePoint"), then normalise to a valid icon filename.
  const rawIconKey = connectorKey
    || (capabilityName ? capabilityServiceName(capabilityName) || capabilityName.split(' - ')[0] : undefined);
  const iconKey = rawIconKey ? normalizeConnectorIconKey(rawIconKey) : undefined;
  const icon = iconKey ? (
    <img
      src={`/component-icons/${iconKey}16.svg`}
      alt={iconKey}
      style={{ width: 12, height: 12 }}
      onError={e => { (e.target as HTMLImageElement).style.display = 'none'; }}
    />
  ) : undefined;
  return (
    <>
      {before}
      <ComponentPill
        label={pillLabel}
        editText={fullName}
        icon={icon}
        error={error}
        onClick={error && onErrorClick
          ? (e: React.MouseEvent<HTMLSpanElement>) => { e.stopPropagation(); onErrorClick(); }
          : onPillClick ? (e: React.MouseEvent<HTMLSpanElement>) => onPillClick(fullName, e) : undefined}
      />
      {after}
    </>
  );
}

