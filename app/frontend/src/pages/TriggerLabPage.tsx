function buildMakerAdvisory(
  mode: 'partial' | 'fail',
  failedStep: LabCoTStep | undefined,
  scenario: AgentScenario,
): string {
  const stepLabel   = failedStep?.label ?? scenario.expectedActions[0] ?? 'a required step';
  const connKey     = failedStep?.connectorKey ?? guessConnector(failedStep?.label ?? '');
  const connectorRef = connKey ? `the **${connKey}** connector` : 'a required connector';

  if (mode === 'partial') {
    return `One capability didn't complete: **${stepLabel}**.\n\nThis step requires ${connectorRef} to be configured for this agent. Go to **Build → Capabilities** and add the appropriate action to enable it.`;
  }
  // fail
  return `The workflow stopped because ${connectorRef} isn't configured or the agent lacks permission to access it.\n\nGo to **Build → Capabilities**, add the required connector, and verify the agent has the necessary permissions.`;
}

function buildSimResponse(mode: 'pass' | 'partial' | 'fail', scenario: AgentScenario): string {
  const actions = scenario.expectedActions;

  // Extract a meaningful subject from story fields (customer name, company, etc.)
  const fieldMap = scenario.storyFields.reduce<Record<string, string>>(
    (acc, f) => ({ ...acc, [f.key]: f.value }), {},
  );
  const subject =
    fieldMap.customer ?? fieldMap.company ?? fieldMap.client ??
    fieldMap.name ?? fieldMap.requester ?? fieldMap.opportunity ??
    Object.values(fieldMap)[0] ?? '';
  const forSubject = subject ? ` for **${subject}**` : '';

  if (mode === 'pass') {
    const actionLines = actions.map(a => `- ${a}`).join('\n');
    return `I've completed all the requested tasks${forSubject}. Here's a summary of what was done:\n\n${actionLines}\n\nLet me know if you need any adjustments or have follow-up questions.`;
  }

  if (mode === 'partial') {
    const successCount = Math.ceil(actions.length * 0.6);
    const succeeded    = actions.slice(0, successCount);
    const firstFailed  = actions[successCount];
    const doneLines    = succeeded.map(a => `- ${a}`).join('\n');
    const failNote     = firstFailed
      ? `\n\nI wasn't able to ${firstFailed.charAt(0).toLowerCase() + firstFailed.slice(1)}. You may want to follow up on this step manually.`
      : '';
    return `Here's what I was able to complete${forSubject}:\n\n${doneLines}${failNote}`;
  }

  // fail
  const firstAction = (actions[0] ?? 'the first step').toLowerCase();
  return `I'm sorry, I wasn't able to complete this request${forSubject}. I ran into a connection issue when trying to ${firstAction}.\n\nThis is likely a connector configuration problem. Please verify your connector settings in Build and try again.`;
}

function buildSimAssessment(mode: 'pass' | 'partial' | 'fail', expectedActions: string[]): AssessmentResult[] {
  if (mode === 'pass') {
    return expectedActions.map(action => ({ action, covered: true }));
  }
  if (mode === 'partial') {
    const successCount = Math.ceil(expectedActions.length * 0.6);
    return expectedActions.map((action, i) => ({ action, covered: i < successCount }));
  }
  return expectedActions.map(action => ({ action, covered: false }));
}

// Generates 3 realistic follow-up messages a user might send after the agent's response.
async function generateContinuationSuggestions(scenario: AgentScenario, agentResponse: string): Promise<string[]> {
  try {
    const prompt = `An AI agent just responded to this scenario: "${scenario.title}". Agent's response (excerpt): "${agentResponse.slice(0, 300)}". Generate exactly 3 short, realistic follow-up messages a user might send next (approvals, rejections, follow-up questions, requests for changes). Return a JSON array of strings only, no explanation. Example: ["Looks good, please send it", "Can you update the price to $1,500?", "Send a copy to my manager too"]`;
    const raw = await callModel({ model: 'fast', maxTokens: 200, messages: [{ role: 'user', content: prompt }] });
    const match = raw.match(/\[[\s\S]*?\]/);
    if (match) return JSON.parse(match[0]).slice(0, 3);
  } catch { /* localStorage / parse — non-fatal */ }
  return ['Looks good, go ahead', 'Can you make a change?', 'Send this to the team'];
}

