  const generateStressTestReply = async (
    history: ConversationTurn[],
    scenario: AgentScenario,
    turn: number,
  ): Promise<{ message: string; shouldContinue: boolean }> => {
    const lastAssistant = [...history].reverse().find(m => m.role === 'assistant')?.content ?? '';
    const expectedActions = scenario.expectedActions.join('\n- ');

    // Turn-by-turn strategy designed to let the full flow complete, then probe edge cases.
    // Turn 1 is critical: if the agent is waiting for consent/confirmation, give it — otherwise
    // multi-step flows (consent gates, approvals, confirmations) can never demonstrate success.
    const strategy = [
      `Check whether the agent's initial response is appropriate and complete. Ask a short, natural follow-up that moves the conversation forward — don't verify things that clearly haven't happened yet.`,
      `CRITICAL: Read the agent's last response carefully. If the agent asked for your confirmation, consent, or a decision (e.g. "shall I proceed?", "do you confirm?", "would you like me to go ahead?", "yes or no"), respond affirmatively so the agent can demonstrate completing the action (e.g. "Yes, please go ahead." or "Yes, that's correct."). If the agent did NOT ask for confirmation, ask a realistic follow-up or request a slight variation.`,
      `Introduce a realistic complication that genuinely happens in this domain — a missing piece of information, an ambiguous value, a second item to process, or a boundary condition. Stay helpful, not adversarial.`,
      `Test a realistic edge case specific to this scenario. Stay in-character as a user with a legitimate need.`,
    ];
    const angle = strategy[Math.min(turn, strategy.length - 1)];

    const prompt = `You are simulating a realistic user in a test of an AI agent. Your goal is to help verify that the agent's tools, knowledge sources, and multi-step flows work end-to-end — NOT to be difficult.

Scenario: ${scenario.title}
Expected actions the agent should perform:
- ${expectedActions}

Agent's last response:
${lastAssistant.slice(0, 800)}

Your task for this turn: ${angle}

Rules:
- 1-2 sentences max, written as a natural user message
- Stay grounded in what the agent just said
- Do NOT be hostile, sarcastic, or push back without cause
- If the full scenario has clearly completed (all expected actions demonstrated, task done), respond with: {"done": true}

Respond with JSON: {"message": "...", "done": false} or {"done": true}`;

    try {
      const raw = await Promise.race([
        callModel({
          model: 'fast',
          maxTokens: 200,
          messages: [{ role: 'user', content: prompt }],
        }),
        new Promise<never>((_, reject) =>
          setTimeout(() => reject(new Error('generateStressTestReply timed out')), 20_000)
        ),
      ]);
      const match = raw.match(/\{[\s\S]*?\}/);
      if (!match) throw new Error('No JSON');
      const parsed = JSON.parse(match[0]);
      if (parsed.done) return { message: '', shouldContinue: false };
      return { message: parsed.message, shouldContinue: true };
    } catch {
      return { message: 'Can you walk me through exactly what just happened?', shouldContinue: turn < 2 };
    }
  };

